// 内水浸水想定区域データの都道府県別対応状況。
//
// 【重要・2026-09-29の調査結果】ハザードマップポータルサイトの公式データ
// 仕様（opendata.html）および、オープンデータ化を許諾した市町村の一覧CSV
// （naisui.csv）を実際に確認した結果に基づく。
// - 都道府県コード付きの配信URL（02_naisui_pref_data/{コード}/）自体は
//   滋賀(25)・京都(26)・大阪(27)・兵庫(28)に存在するが、これは
//   「その都道府県全域でデータが使える」ことを意味しない。実際に
//   オープンデータとして許諾されている市町村はごく一部で、近畿全体でも
//   8市町村のみだった（滋賀:日野町・豊郷町、京都:綾部市・大山崎町、
//   大阪:堺市、兵庫:尼崎市・たつの市・上郡町）。大阪市自体がこの
//   タイルに含まれるかは今回の調査では確認できていない。
// - 奈良(29)・和歌山(30)は配信URL自体が公式資料の一覧表に存在せず、
//   許諾市町村も0件だった。
//
// 【今回のPhaseでの扱い】上記の不確実性を踏まえ、既存運用がある大阪府
// (27)のみ"supported"として現状維持し、URLは存在するが実際のカバー範囲を
// 確認しきれていない滋賀・京都・兵庫は"unknown"（「使える」とも「使えない」
// とも断定しない）、配信URL自体が存在しない奈良・和歌山は"unsupported"と
// する。
//
// 【重要・Phase 6（2026-09-30）の方針】内水氾濫は、アプリ全体で現行の
// 対象外とした（危険度判定・ルート評価・地図表示・通知のいずれでも評価しない。
// 切り替えはlib/region/capability.tsのINLAND_FLOOD_EVALUATION_ENABLEDの1か所）。
// この表は「将来、市区町村単位で内水氾濫を再導入する際の調査記録」として
// 残しているものであり、現在のアプリ動作の判断には使われない。
//
// 【Phase 6の実測結果（2026-09-30）】各府県コードのタイル配信URLに対し、
// 主要都市と許諾済み市町村の周辺3×3タイル（z13/15/17）を実際に取得した:
// - 大阪市役所・東大阪・大津・京都市・神戸・奈良市・和歌山市: 全ズームで0/9
//   （＝府県コードのURLが存在しても、主要都市には内水氾濫データが無い）
// - 堺市・日野町・豊郷町・綾部市・大山崎町・尼崎市・たつの市: いずれもタイルを取得できた
// - 奈良(29)・和歌山(30): 府県単位の配信自体が404
// つまり近畿で実際に使えるのは許諾済み8市町村のみで、大阪市も含まれない。
// Phase 2〜5で"27"を"supported"としていたのは「従来のURLを使う実装を維持する」
// ための値であり、データの存在を裏付けるものではなかったため、Phase 6で
// 実態に合わせて滋賀・京都・兵庫と同じ"unknown"（府県内の一部市町村のみ）に訂正した。
//
// 【将来の拡張方針・今回は未実装】内水氾濫は本来、都道府県単位ではなく
// 市区町村単位で提供状況が大きく異なる（本ファイル冒頭の調査結果参照）。
// そのため、将来的により正確な判定が必要になった場合は、この関数を
// 「prefectureCodeのみで引く単純なテーブル」から「市区町村コード
// (MunicipalityCode)単位のオーバーライドテーブルを先に引き、無ければ
// 都道府県単位のテーブルにフォールバックする」構造へ拡張できる
// （例: getInlandFloodAvailability(prefectureCode, municipalityCode?)
// のようにmunicipalityCodeを追加の任意引数にし、
// MUNICIPALITY_OVERRIDE[municipalityCode] があればそれを優先する）。
// 今回のPhaseでは、この拡張のための大規模な構造変更は行わず、
// 既存のprefectureCodeのみの単純な関数のまま維持している。

import type { CapabilityStatus } from "./capability.ts";
import type { PrefectureCode } from "./types.ts";

const INLAND_FLOOD_AVAILABILITY: Record<PrefectureCode, CapabilityStatus> = {
  "25": "unknown", // 滋賀県: 府県単位の配信URLは存在。実データを確認できたのは日野町・豊郷町のみ（大津市は無し）
  "26": "unknown", // 京都府: 同上。綾部市・大山崎町のみ（京都市は無し）
  "27": "unknown", // 大阪府: 同上。堺市のみ（大阪市・東大阪市は無し。2026-09-30実測）
  "28": "unknown", // 兵庫県: 同上。尼崎市・たつの市・上郡町のみ（神戸市は無し）
  "29": "unsupported", // 奈良県: 配信URL自体が存在しない（2026-09-30時点）
  "30": "unsupported", // 和歌山県: 配信URL自体が存在しない（2026-09-30時点）
};

export function getInlandFloodAvailability(prefectureCode: PrefectureCode): CapabilityStatus {
  return INLAND_FLOOD_AVAILABILITY[prefectureCode];
}
