// 新機能調査（河川ライブカメラ・水位を用いた危険度評価）: 型のスケルトンのみ。
//
// 【重要・調査結果 2026-09-28】大阪市周辺の河川水位・河川ライブカメラを、
// 無料かつ権利関係が明確な形で自動取得できる公式データソースは、今回の
// 調査時点では確認できなかった。
// - 国土交通省「川の防災情報」: 規約上、ツールによる定期的な自動収集は
//   行わないよう明記されている（正式な配信サービスの利用を案内している）
// - 水防災オープンデータ提供サービス（河川情報センター）: 技術的には
//   水位・カメラとも充実しているが、有償契約が必要
// - 大阪市河川監視システム（11地点、水位＋画像）: 告知ページにCC-BY表記が
//   あるが、実データ（外部ドメインosaka-city-kasen.jp）への適用範囲が
//   文面上断定できず、大阪市河川課への確認が前提
// - 近畿地方整備局の河川事務所ライブカメラ: 利用規約の明記がなくグレー
//
// そのため、この型・Providerは「将来、許諾が取れた実データソースへ
// 差し替えられる」ことだけを目的としたスケルトンであり、現時点では
// 実際の水位・カメラ画像は一切取得しない。常にlevel="unknown"を返し、
// 公式サイトへのリンクのみを提供する（このアプリ独自の判定であることが
// 明確になるよう、判定材料を持たない状態ではlevelを断定しない）。

export type RiverStatusLevel = "normal" | "caution" | "warning" | "danger" | "unknown";

export type RiverStatusSource = {
  /** 出典の名称（例:「大阪府河川防災情報ポータル」）。 */
  name: string;
  /** 出典URL。ユーザーが自分の目で最新状況を確認できる公式ページを指す。 */
  url: string;
};

export type RiverStatus = {
  /** 対象河川名。特定できない場合はnull（エリア全体の代表情報として扱う）。 */
  riverName: string | null;
  level: RiverStatusLevel;
  /** 実データを取得できた日時（ISO8601）。取得していない/できない場合はnull。 */
  fetchedAt: string | null;
  /** 実際にアクセスして確認済みの公式サイトへのリンク（複数可）。 */
  sources: RiverStatusSource[];
  /** 利用者向けの注記（例:「自動取得未対応のため公式サイトをご確認ください」）。 */
  note: string;
};
